#!/usr/bin/env node
/**
 * Run each scenario variant's documented command and write static result
 * JSON under apps/web/public/results/ for the scenario Results panel.
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const examplesRoot = path.join(root, "examples");
const outRoot = path.join(root, "apps/web/public/results");
const capturedAt = new Date().toISOString();

function walkScenarios(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walkScenarios(full, acc);
    else if (entry.name === "scenario.json") {
      acc.push(JSON.parse(fs.readFileSync(full, "utf8")));
    }
  }
  return acc;
}

function runVariant(variant) {
  const cwd = path.join(root, variant.run.cwd);
  const started = Date.now();
  const result = spawnSync(variant.run.command, {
    cwd,
    shell: true,
    encoding: "utf8",
    env: { ...process.env, FORCE_COLOR: "0", NO_COLOR: "1", CI: "1" },
    maxBuffer: 4 * 1024 * 1024,
  });
  const stdout = result.stdout ?? "";
  const stderr = result.stderr ?? "";
  const combined = [stdout, stderr].filter(Boolean).join(stdout && stderr ? "\n" : "");
  // Drop host-env npm noise that is not part of the example output.
  const output = combined
    .split("\n")
    .filter((line) => !/npm warn Unknown env config/i.test(line))
    .join("\n")
    .replace(/\nnpm notice[\s\S]*$/m, "")
    .trimEnd();
  return {
    exitCode: result.status ?? 1,
    ok: (result.status ?? 1) === 0,
    durationMs: Date.now() - started,
    output: output || "(no output)",
  };
}

const scenarios = walkScenarios(examplesRoot).sort((a, b) => a.id.localeCompare(b.id));
if (!scenarios.length) {
  console.error("No scenarios found under examples/");
  process.exit(1);
}

fs.rmSync(outRoot, { recursive: true, force: true });
fs.mkdirSync(outRoot, { recursive: true });

const manifestVariants = [];
let failures = 0;

for (const scenario of scenarios) {
  const scenarioDir = path.join(outRoot, scenario.id);
  fs.mkdirSync(scenarioDir, { recursive: true });

  for (const variant of scenario.variants) {
    process.stdout.write(`Capturing ${scenario.id} / ${variant.framework}... `);
    const run = runVariant(variant);
    const record = {
      scenarioId: scenario.id,
      framework: variant.framework,
      label: variant.label,
      cwd: variant.run.cwd,
      command: variant.run.command,
      exitCode: run.exitCode,
      ok: run.ok,
      durationMs: run.durationMs,
      capturedAt,
      output: run.output,
    };
    fs.writeFileSync(path.join(scenarioDir, `${variant.framework}.json`), `${JSON.stringify(record, null, 2)}\n`);
    manifestVariants.push({
      scenarioId: scenario.id,
      framework: variant.framework,
      ok: run.ok,
      exitCode: run.exitCode,
      durationMs: run.durationMs,
    });
    if (!run.ok) failures += 1;
    console.log(run.ok ? `ok (${run.durationMs}ms)` : `FAIL exit ${run.exitCode}`);
  }
}

const manifest = {
  capturedAt,
  source: process.env.GITHUB_ACTIONS === "true" ? "ci" : "local",
  gitSha: process.env.GITHUB_SHA ?? null,
  variantCount: manifestVariants.length,
  failureCount: failures,
  variants: manifestVariants,
};

fs.writeFileSync(path.join(outRoot, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
fs.writeFileSync(
  path.join(outRoot, "README.md"),
  `# Cached scenario results

Generated by \`npm run capture:results\` (CI before site build).

These files are static fixtures shown in the scenario **Results** panel.
They are not live test runs in the browser.

- \`manifest.json\` — capture metadata and pass/fail summary
- \`<scenario-id>/<framework>.json\` — stdout/stderr + exit code for one variant
`,
);

console.log(
  `\nWrote ${manifestVariants.length} result(s) to apps/web/public/results/ (${failures} failure(s)).`,
);

if (failures > 0) {
  process.exit(1);
}
